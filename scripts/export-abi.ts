// Copies the compiled ABIs into a typed module shared by the web app and the scripts.
import { readFileSync, writeFileSync } from "node:fs";

const read = (name: string) =>
  JSON.stringify(JSON.parse(readFileSync(`contracts/out/${name}.sol/${name}.json`, "utf8")).abi, null, 2);

writeFileSync(
  "web/src/lib/abi.ts",
  `// Generated by scripts/export-abi.ts. Do not edit.
export const hundiAbi = ${read("HundiInvoice")} as const;

export const registryAbi = ${read("ParticipantRegistry")} as const;
`,
);
console.log("Wrote web/src/lib/abi.ts");
